// Builds js/areas-art.js: the isometric figures of the "Specjalizacje" cards.
// The figures are drawn in the style and on the engine of lucasmarkes/hairline
// (MIT, see scripts/hairline/LICENSE): kernel.js is that engine untouched, and
// scripts/hairline/figures/*.js are the six figures made for this site.
// Run: node scripts/build-areas-art.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const kernel = readFileSync(here('./hairline/kernel.js'), 'utf8').trimEnd();
const figures = readdirSync(here('./hairline/figures')).filter((f) => f.endsWith('.js')).sort()
  .map((f) => readFileSync(here('./hairline/figures/' + f), 'utf8').trim());

const out = `/* GENERATED by scripts/build-areas-art.mjs: do not edit by hand.
   Isometric line figures for the "Specjalizacje" cards, on the engine of
   lucasmarkes/hairline (MIT). Each [data-hl="name"] element gets its figure. */
(function () {
${kernel}

var FIGURES = {};
function hairline(f) { FIGURES[f.name] = f; }
${figures.map((f) => `(function () {\n${f}\n})();`).join('\n\n')}

function start() {
  HL.inject(document);
  Array.prototype.forEach.call(document.querySelectorAll('[data-hl]'), function (stage) {
    var f = FIGURES[stage.getAttribute('data-hl')];
    if (!f || stage.firstChild) return;
    stage.setAttribute('data-hairline', f.name);
    var svg = HL.mk('svg', { viewBox: '0 0 400 320', 'aria-hidden': 'true' }, stage);
    f.mount({ stage: stage, svg: svg, read: { textContent: '' } }, f.range[1]);
  });
}
if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start);
else start();
})();
`;
writeFileSync(here('../js/areas-art.js'), out);
console.log('js/areas-art.js', out.length, 'bytes');
