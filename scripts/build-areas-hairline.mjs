// Builds js/areas-hairline.js: a trimmed copy of @lucasmarkes/hairline (MIT,
// scripts/hairline/vendor/) with only the figures the "Specjalizacje" cards use,
// plus the code that mounts them on [data-hl] elements.
// Run: node scripts/build-areas-hairline.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const src = readFileSync(here('./hairline/vendor/hairline-0.5.1.js'), 'utf8');

// the dist file is a list of sections, each started by "// src/<file>.ts"
const sections = {};
const marks = [...src.matchAll(/^\/\/ src\/(.+)\.ts$/gm)];
marks.forEach((m, i) => {
  sections[m[1]] = src.slice(m.index, i + 1 < marks.length ? marks[i + 1].index : src.length);
});

// figure name on the page -> the package's function, with a Polish accessible name
const USE = {
  riffle: 'Teczki z aktami do przeglądania',
  cabinet: 'Szafa z szufladami na akta',
  loupe: 'Lupa nad kartką',
  padlock: 'Kłódka',
  vault: 'Sejf z pokrętłem'
};

const core = ['core/styles', 'core/iso', 'core/motion', 'core/stage', 'intensity', 'mount'];
const figs = ['figures/cabinet', 'figures/loupe', 'figures/padlock', 'figures/riffle-geometry', 'figures/riffle', 'figures/vault'];
const index = sections['index'];
const wrappers = Object.keys(USE).map((name) => {
  const m = index.match(new RegExp('^function ' + name + '\\(el, options\\) \\{[\\s\\S]*?\\n\\}\\n', 'm'));
  if (!m) throw new Error('no wrapper for ' + name);
  return m[0].replace(/label: "[^"]*"/, (l) => l); // the label is overridden per card below
});

const out = `/* GENERATED by scripts/build-areas-hairline.mjs: do not edit by hand.
   Trimmed from @lucasmarkes/hairline 0.5.1 (MIT). */
(function () {
${[...core, ...figs].map((k) => sections[k].trimEnd()).join('\n\n')}

${wrappers.join('\n')}
var LABELS = ${JSON.stringify(USE)};
var FIGURES = { ${Object.keys(USE).join(', ')} };

function mountAreas() {
  document.querySelectorAll('[data-hl]').forEach(function (el) {
    var name = el.getAttribute('data-hl');
    if (!FIGURES[name] || el.firstChild) return;
    FIGURES[name](el, { label: LABELS[name] });
  });
}
if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', mountAreas);
else mountAreas();
})();
`;
writeFileSync(here('../js/areas-hairline.js'), out);
console.log('js/areas-hairline.js', out.length, 'bytes');
